"""
Run the whole pipeline end to end and write outputs/INSIGHTS_REPORT.md.

    python python/run_all.py

Every number in the report is computed from the data in this run; nothing is typed in by hand.
"""
import json
import time

import config as C
import s01_clean_transform
import s02_build_database
import s03_eda_sales
import s04_customer_analytics
import s05_statistical_tests

STEPS = [
    ("1/5 Clean & transform", s01_clean_transform),
    ("2/5 SQL database + queries", s02_build_database),
    ("3/5 EDA & charts", s03_eda_sales),
    ("4/5 Customer analytics (cohorts, RFM)", s04_customer_analytics),
    ("5/5 Statistical tests", s05_statistical_tests),
]


def fmt_money(x):
    return f"R$ {x / 1e6:,.2f}M" if x >= 1e6 else f"R$ {x:,.0f}"


def change(x):
    """12.3 -> '12.3% higher', -4 -> '4.0% lower'."""
    if x is None:
        return "n/a"
    return f"{abs(x):.1f}% {'higher' if x >= 0 else 'lower'}"


def p_text(p):
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


def write_report(m: dict) -> None:
    seg = m.get("rfm_segments", {})
    champions = seg.get("Champions", {})
    at_risk = seg.get("At Risk High-Value", {})
    issues = m["cleaning_issues"]
    lines = f"""# Olist E-Commerce Analytics: Insights Report

*Generated by `python/run_all.py` from {m['raw_orders']:,} orders placed between {m['first_purchase']} and {m['last_purchase']}.
Trend figures use complete months only ({C.ANALYSIS_START_MONTH} to {C.ANALYSIS_END_MONTH}).*

## 1. Business snapshot
| KPI | Value |
|---|---|
| Valid orders (excl. canceled/unavailable) | {m['valid_orders']:,} |
| Unique customers | {m['customers_with_valid_order']:,} |
| GMV (price + freight) | {fmt_money(m['gmv'])} |
| Product revenue | {fmt_money(m['product_revenue'])} |
| Average order value | R$ {m['aov']:,.2f} |
| Average review score | {m['avg_review']} / 5 |
| Late-delivery rate | {m['late_delivery_pct']}% |
| Repeat-customer rate | {m['repeat_customer_pct']}% |

## 2. Key findings

**Growth.** Jan-Aug 2018 GMV was {change(m.get('yoy_gmv_growth_pct'))} than Jan-Aug 2017
(orders {change(m.get('yoy_orders_growth_pct'))}). The single biggest month was {m['peak_month']}
({m['peak_month_orders']:,} orders vs a median month of {m['median_month_orders']:,.0f}).

**Retention is the biggest problem.** Only {m['repeat_customer_pct']}% of customers ever placed a
second order, and they generate {m['repeat_customer_gmv_pct']}% of GMV. On average only
{m['avg_month1_retention_pct']}% of a month's new customers buy again the following month
(across {m['cohorts_analysed']} cohorts). Growth depends almost entirely on new-customer acquisition.

**Late delivery damages satisfaction, and the effect is statistically significant.**
{m['late_delivery_pct']}% of delivered orders arrived after the promised date. Late orders average
{m['avg_review_late']} stars vs {m['avg_review_ontime']} for on-time orders, and
{m['neg_review_pct_late']}% of late orders get a 1-2 star review vs {m['neg_review_pct_ontime']}% on time
(relative risk {m['neg_review_relative_risk']}x). Mann-Whitney U {p_text(m['mw_p_value'])};
chi-square {p_text(m['chi2_p_value'])}; 95% CI for the drop in mean score:
{m['review_diff_ci_low']} to {m['review_diff_ci_high']} stars.

**Promises are padded.** Orders take {m['avg_delivery_days']} days on average against a promised
{m['avg_promised_days']} days. The worst state for lateness is {m.get('worst_late_state', 'n/a')}
({m.get('worst_late_state_pct', 'n/a')}% late); the best is {m.get('best_late_state', 'n/a')}
({m.get('best_late_state_pct', 'n/a')}%).

**Revenue is concentrated.** {m['categories_for_80pct_revenue']} of {m['categories_total']} categories
make 80% of product revenue; the top 3 ({', '.join(m['top3_categories'])}) make
{m['top3_categories_share_pct']}%. {m['top_state']} alone is {m['top_state_share_pct']}% of GMV, and
the top 3 states are {m['top3_states_share_pct']}%.

**Freight is a hidden price.** Freight adds {m.get('overall_freight_pct', 'n/a')}% on top of product
price overall, and {m.get('highest_freight_pct', 'n/a')}% in {m.get('highest_freight_category', 'n/a')}.

**Payments.** Credit card is the main method for {m['credit_card_share_pct']}% of orders
(boleto {m['boleto_share_pct']}%); {m['cc_orders_with_installments_pct']}% of card orders use instalments.

**When people buy.** The busiest weekday is {m['busiest_weekday']}, the quietest {m['quietest_weekday']};
{m['share_orders_10_to_22h_pct']}% of orders are placed between 10:00 and 22:59.

**RFM.** Champions are {champions.get('pct_customers', 'n/a')}% of customers but
{champions.get('pct_gmv', 'n/a')}% of GMV. "At Risk High-Value" customers ({at_risk.get('pct_customers', 'n/a')}%
of customers, average spend R$ {at_risk.get('avg_gmv', 'n/a')}) are the best win-back target.

## 3. Recommendations
1. **Launch a second-purchase programme.** Send a post-delivery voucher and category-based
   recommendations to first-time buyers. Even moving the repeat rate from
   {m['repeat_customer_pct']}% up by a few points adds revenue without acquisition cost.
2. **Fix delivery promises first in the worst states.** Set state-specific estimated dates and
   carrier SLAs, starting with {m.get('worst_late_state', 'the worst state')}. Lateness is the main
   measurable driver of 1-2 star reviews.
3. **Seller quality programme.** Track the seller scorecard (`sql/06`). Warn or coach sellers with
   an average review below 3.5 or more than 15% late deliveries.
4. **Win back "At Risk High-Value" customers** with targeted offers in their past categories.
5. **Freight-aware pricing.** Test free-shipping thresholds in high-freight categories,
   where shipping cost is a large share of the basket.

## 4. Data quality notes
| Issue found in raw data | Rows | Handling |
|---|---:|---|
| Orders with multiple reviews | {issues['orders_with_multiple_reviews']:,} | kept the latest review per order |
| Products without a category | {issues['products_without_category']:,} | labelled "Unknown" |
| Payments 'not_defined' / zero value | {issues['payments_not_defined_or_zero']:,} | removed |
| Delivered status but no delivery date | {issues['delivered_status_without_date']:,} | excluded from delivery metrics |
| Delivery date before purchase date | {issues['delivered_before_purchase']:,} | excluded from delivery metrics |
| Orders without items | {issues['orders_without_items']:,} | kept; contribute 0 revenue |
| Payment total differs from items + freight by > R$1 | {issues['orders_payment_vs_gmv_diff_gt_1']:,} | GMV uses items + freight |

## 5. Limitations
- Olist is one marketplace, 2016-2018, Brazil. The numbers describe that business, not e-commerce in general.
- Correlation is not causation: late orders may also differ in product, region or seller.
  A controlled test (for example by carrier) would be needed to measure the causal effect.
- Reviews exist only for customers who chose to leave one.
"""
    (C.OUTPUT_DIR / "INSIGHTS_REPORT.md").write_text(lines, encoding="utf-8")


def main():
    metrics = {}
    for label, module in STEPS:
        t = time.time()
        print(f"\n{'=' * 70}\n{label}\n{'=' * 70}")
        metrics.update(module.run())
        print(f"[{label} done in {time.time() - t:.1f}s]")
    (C.OUTPUT_DIR / "metrics.json").write_text(json.dumps(metrics, indent=2, default=str), encoding="utf-8")
    write_report(metrics)
    print(f"\nDone. Report: {C.OUTPUT_DIR / 'INSIGHTS_REPORT.md'}")


if __name__ == "__main__":
    main()
